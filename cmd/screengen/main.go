package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type Screen struct {
	ID      string
	Package string
	Alias   string
	Import  string
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, "screen generator:", err)
		os.Exit(1)
	}
}

func generate() error {
	root, err := os.Getwd()
	if err != nil {
		return err
	}

	module, err := readModulePath(filepath.Join(root, "go.mod"))
	if err != nil {
		return err
	}

	screensDir := filepath.Join(root, "screens")

	entries, err := os.ReadDir(screensDir)
	if err != nil {
		return fmt.Errorf("read screens directory: %w", err)
	}

	var screens []Screen

	for _, entry := range entries {
		if !entry.IsDir() || strings.HasPrefix(entry.Name(), ".") ||
			strings.HasPrefix(entry.Name(), "_") {
			continue
		}

		dir := filepath.Join(screensDir, entry.Name())

		pkg, found, err := discoverScreen(dir)
		if err != nil {
			return fmt.Errorf("inspect screen %q: %w", entry.Name(), err)
		}

		// Directories without the View(visible bool) ui.View
		// function are not modal screens.
		if !found {
			fmt.Printf("Skipping %-16s (no View(visible bool) function)\n", entry.Name())
			continue
		}

		screens = append(screens, Screen{
			ID:      entry.Name(),
			Package: pkg,
			Import:  module + "/screens/" + entry.Name(),
		})
	}

	sort.Slice(screens, func(i, j int) bool {
		return screens[i].ID < screens[j].ID
	})

	// Generate unique import aliases.
	usedAliases := make(map[string]int)

	for i := range screens {
		base := screens[i].Package
		usedAliases[base]++

		if usedAliases[base] == 1 {
			screens[i].Alias = base
		} else {
			screens[i].Alias = fmt.Sprintf("%s%d", base, usedAliases[base])
		}
	}

	source, err := buildSource(screens)
	if err != nil {
		return err
	}

	outputDir := filepath.Join(root, "app")
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return err
	}

	output := filepath.Join(outputDir, "screens_gen.go")

	if err := os.WriteFile(output, source, 0644); err != nil {
		return err
	}

	fmt.Printf("\nGenerated %s\n", output)
	fmt.Printf("Registered %d modal screens.\n", len(screens))

	return nil
}

func readModulePath(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}

	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(line)

		if len(fields) >= 2 && fields[0] == "module" {
			return strings.Trim(fields[1], `"`), nil
		}
	}

	return "", fmt.Errorf("module path not found in go.mod")
}

func discoverScreen(dir string) (string, bool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", false, err
	}

	fset := token.NewFileSet()
	packageName := ""
	found := false

	for _, entry := range entries {
		name := entry.Name()

		if entry.IsDir() ||
			!strings.HasSuffix(name, ".go") ||
			strings.HasSuffix(name, "_test.go") ||
			strings.HasPrefix(name, ".") ||
			strings.HasPrefix(name, "_") {
			continue
		}

		file, err := parser.ParseFile(
			fset,
			filepath.Join(dir, name),
			nil,
			parser.AllErrors,
		)
		if err != nil {
			return "", false, err
		}

		if packageName == "" {
			packageName = file.Name.Name
		} else if packageName != file.Name.Name {
			return "", false, fmt.Errorf("multiple package names in %s", dir)
		}

		for _, declaration := range file.Decls {
			fn, ok := declaration.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || fn.Name.Name != "View" {
				continue
			}

			if validViewSignature(fn) {
				found = true
			}
		}
	}

	return packageName, found, nil
}

func validViewSignature(fn *ast.FuncDecl) bool {
	if fn.Type.Params == nil || fn.Type.Results == nil {
		return false
	}

	if len(fn.Type.Params.List) != 1 ||
		len(fn.Type.Results.List) != 1 {
		return false
	}

	param := fn.Type.Params.List[0]
	result := fn.Type.Results.List[0]

	if len(param.Names) != 1 || param.Names[0].Name != "visible" {
		return false
	}

	paramType, ok := param.Type.(*ast.Ident)
	if !ok || paramType.Name != "bool" {
		return false
	}

	resultType, ok := result.Type.(*ast.SelectorExpr)
	if !ok || resultType.Sel.Name != "View" {
		return false
	}

	pkg, ok := resultType.X.(*ast.Ident)
	if !ok || pkg.Name != "ui" {
		return false
	}

	return true
}

func buildSource(screens []Screen) ([]byte, error) {
	var b bytes.Buffer

	fmt.Fprintln(&b, "// Code generated by cmd/screengen. DO NOT EDIT.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package app")
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "import (")

	if len(screens) > 0 {
		fmt.Fprintln(&b, `"github.com/golang-gui/goui/ui"`)
	}

	for _, screen := range screens {
		fmt.Fprintf(
			&b,
			"%s %s\n",
			screen.Alias,
			strconv.Quote(screen.Import),
		)
	}

	fmt.Fprintln(&b, ")")
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "// GeneratedScreen describes a registered modal screen.")
	fmt.Fprintln(&b, "type GeneratedScreen struct {")
	fmt.Fprintln(&b, "\tID string")
	fmt.Fprintln(&b, "\tBuild func(visible bool) ui.View")
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "// GeneratedScreens returns all discovered modal screens.")
	fmt.Fprintln(&b, "func GeneratedScreens() []GeneratedScreen {")
	fmt.Fprintln(&b, "\treturn []GeneratedScreen{")

	for _, screen := range screens {
		fmt.Fprintf(
			&b,
			"\t\t{ID: %q, Build: %s.View},\n",
			screen.ID,
			screen.Alias,
		)
	}

	fmt.Fprintln(&b, "\t}")
	fmt.Fprintln(&b, "}")

	return format.Source(b.Bytes())
}
